import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { palette } from '../src/colors';
import {
  animation,
  durations,
  easings,
  fontFamily,
  iconSizes,
  keyframes,
  radii,
  radius,
} from '../src/foundation';
import { heroUIVariables } from '../src/heroui';
import { semanticColorNames, semanticValues } from '../src/semantic';
import { typeScale, typeStyleKey, type TypeStyleName } from '../src/typography';

const distDir = resolve(dirname(fileURLToPath(import.meta.url)), '../dist');
mkdirSync(distDir, { recursive: true });

const header = '/* Generated by @halth/design-system-tokens — do not edit. */\n';

const cssVars = (values: Record<string, string>) =>
  Object.entries(values)
    .map(([name, value]) => `  --${name}: ${value};`)
    .join('\n');

const variablesCss = `${header}:root {
${cssVars(semanticValues)}
  --radius: ${radius};
}
`;

const paletteVars = Object.entries(palette).flatMap(([name, value]) =>
  typeof value === 'string'
    ? [`  --color-${name}: ${value};`]
    : Object.entries(value).map(([shade, hex]) =>
        shade === 'DEFAULT'
          ? `  --color-${name}: ${hex};`
          : `  --color-${name}-${shade}: ${hex};`
      )
);

const typeScaleVars = Object.entries(typeScale).flatMap(([name, style]) => {
  const key = `--text-${typeStyleKey(name as TypeStyleName)}`;
  return [
    `  ${key}: ${style.fontSize};`,
    `  ${key}--line-height: ${style.lineHeight};`,
    ...('letterSpacing' in style ? [`  ${key}--letter-spacing: ${style.letterSpacing};`] : []),
    ...('fontWeight' in style ? [`  ${key}--font-weight: ${style.fontWeight};`] : []),
  ];
});

const semanticVars = semanticColorNames
  .filter((name) => !(name in palette))
  .map((name) => `  --color-${name}: var(--${name});`);

const semanticColorValues = Object.fromEntries(
  Object.entries(semanticValues).map(([name, channels]) => [name, `hsl(${channels})`])
);

const keyframesCss = Object.entries(keyframes)
  .map(([name, frames]) => {
    const steps = Object.entries(frames)
      .map(
        ([step, props]) =>
          `    ${step} { ${Object.entries(props)
            .map(([prop, value]) => `${prop}: ${value};`)
            .join(' ')} }`
      )
      .join('\n');
    return `  @keyframes ${name} {\n${steps}\n  }`;
  })
  .join('\n');

const themeCss = `${header}:root {
${cssVars(semanticColorValues)}
  --radius: ${radius};
${Object.entries(iconSizes)
  .map(([name, value]) => `  --icon-${name}: ${value};`)
  .join('\n')}
${Object.entries(durations)
  .map(([name, value]) => `  --duration-${name}: ${value}ms;`)
  .join('\n')}
}

@theme {
  --font-sans: ${fontFamily.sans.join(', ')};
${typeScaleVars.join('\n')}
${paletteVars.join('\n')}
  --color-primary-foreground: hsl(var(--primary-foreground));
  --color-stone-foreground: hsl(var(--primary-foreground));
  --radius-lg: var(--radius);
  --radius-md: calc(var(--radius) - 2px);
  --radius-sm: calc(var(--radius) - 4px);
${Object.entries(radii)
  .map(([name, value]) => `  --radius-${name}: ${value};`)
  .join('\n')}
${Object.entries(easings)
  .map(([name, value]) => `  --ease-${name}: cubic-bezier(${value.join(', ')});`)
  .join('\n')}
${Object.entries(animation)
  .map(([name, value]) => `  --animate-${name}: ${value};`)
  .join('\n')}
${keyframesCss}
}

@theme inline {
${semanticVars.join('\n')}
}
`;

const herouiCss = `${header}/* Import after '@heroui/styles'. */
@import './theme.css';

:root {
${cssVars(heroUIVariables)}
}
`;

writeFileSync(resolve(distDir, 'variables.css'), variablesCss);
writeFileSync(resolve(distDir, 'theme.css'), themeCss);
writeFileSync(resolve(distDir, 'heroui.css'), herouiCss);
console.log('Wrote dist/variables.css, dist/theme.css and dist/heroui.css');
